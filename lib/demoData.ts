export function getDemoLocationById(locationId: string) {
  const id = Number(locationId);

  if (!Number.isInteger(id)) {
    return null;
  }

  return demoLocations.find((location) => location.id === id) ?? null;
}

export function getDemoMessagesForLocation(locationId: string) {
  const id = Number(locationId);

  if (!Number.isInteger(id)) {
    return [];
  }

  return demoMessages
    .filter((message) => message.location_id === id && message.status === "public")
    .sort((first, second) =>
      second.created_at.localeCompare(first.created_at),
    );
}
